# Turns the Japanese translations of the Qt keymap editor of Mozc
# (gui/config_dialog/keymap_ja.qtts) into a C++ table for the keymap editor
# of mozc_tool: {"Backspace", "左の文字を削除"}, ...
#
# Usage: gen_keymap_strings.py keymap_ja.qtts output.inc

import sys
import xml.etree.ElementTree as ET


def quote(text):
  return '"' + text.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
  tree = ET.parse(sys.argv[1])
  lines = []
  for message in tree.iter('message'):
    source = message.findtext('source')
    translation = message.findtext('translation')
    if source and translation:
      lines.append('{%s, %s},' % (quote(source), quote(translation)))
  with open(sys.argv[2], 'w', encoding='utf-8') as f:
    f.write('// Generated by gen_keymap_strings.py. Do not edit.\n')
    f.write('\n'.join(lines) + '\n')


if __name__ == '__main__':
  main()
